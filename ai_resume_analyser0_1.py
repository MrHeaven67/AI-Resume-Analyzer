# 13. RESUME ANALYSIS
# ============================================================

def analyze_resume(resume_file):

    if resume_file is None:

        return (

            "Please upload a PDF or DOCX resume.",

            None,

            "",

            "",

            ""

        )

    # Extract PDF or DOCX
    text = extract_text_from_resume(
        resume_file
    )

    if text.startswith("ERROR"):

        return (

            text,

            None,

            "",

            "",

            ""

        )

    if len(text.strip()) < 50:

        return (

            "Could not extract enough text from the resume. "
            "Please upload a text-based PDF or DOCX.",

            None,

            "",

            "",

            ""

        )

    # Clean text
    cleaned = clean_text(text)

    # Skills
    resume_skills = extract_skills(cleaned)

    # Job prediction
    predictions = predict_job_roles(cleaned)

    # Top role
    top_role = predictions[0]["Job Role"]

    # Missing skills
    missing_skills = find_missing_skills(

        resume_skills,

        top_role

    )

    # Experience
    experience = extract_experience(text)

    # Education
    education = extract_education(text)

    # Sections
    sections = detect_sections(text)


    # ========================================================
    # CREATE ANALYSIS REPORT
    # ========================================================

    report = "# AI Resume Analysis\n\n"

    report += "## Recommended Job Role\n\n"

    report += f"### {top_role}\n\n"

    report += (

        f"**Match Score:** "
        f"{predictions[0]['Match Score']}%\n\n"

    )

    report += "## Top Job Role Predictions\n\n"

    report += "| Rank | Job Role | Match Score |\n"

    report += "|---:|---|---:|\n"

    for i, result in enumerate(
        predictions[:5],
        1
    ):

        report += (

            f"| {i} | {result['Job Role']} | "
            f"{result['Match Score']}% |\n"

        )


    # Skills
    report += "\n## Skills Detected\n\n"

    if resume_skills:

        for skill in resume_skills:

            report += f"- {skill}\n"

    else:

        report += (
            "No known technical skills detected.\n"
        )


    # Missing skills
    report += "\n## Skills You Could Add\n\n"

    if missing_skills:

        for skill in missing_skills[:10]:

            report += f"- {skill}\n"

    else:

        report += (
            "No major missing skills detected.\n"
        )


    # Education
    report += "\n## Education\n\n"

    if education:

        report += ", ".join(education)

    else:

        report += (
            "Education information not detected."
        )


    # Experience
    report += "\n\n## Experience\n\n"

    report += experience


    # Sections
    report += (
        "\n\n## Resume Sections Detected\n\n"
    )

    for section, detected in sections.items():

        status = (
            "Found"
            if detected
            else
            "Not Found"
        )

        report += (
            f"- **{section}:** {status}\n"
        )


    # Recommendations
    report += "\n## Recommendations\n\n"

    recommendations = []

    if len(resume_skills) < 5:

        recommendations.append(
            "Add more relevant technical skills "
            "to your resume."
        )

    if not sections["Projects"]:

        recommendations.append(
            "Add 2–3 strong projects with "
            "technologies and measurable results."
        )

    if not sections["Certifications"]:

        recommendations.append(
            "Consider adding relevant certifications "
            "or courses."
        )

    if missing_skills:

        recommendations.append(

            "Learn some of the missing skills "
            f"listed above for the {top_role} role."

        )

    if not recommendations:

        recommendations.append(

            "Your resume has a good technical "
            "skill coverage. Continue improving "
            "projects and measurable achievements."

        )

    for recommendation in recommendations:

        report += f"- {recommendation}\n"


    # Raw extracted text
    raw_text = text

    # DataFrame
    prediction_df = pd.DataFrame(
        predictions[:5]
    )

    return (

        report,

        prediction_df,

        ", ".join(resume_skills),

        raw_text,

        top_role

    )


