# 11. MISSING SKILLS
# ============================================================

def find_missing_skills(
    resume_skills,
    predicted_role
):

    role_description = job_roles[
        predicted_role
    ]["description"]

    required_skills = []

    for skill in skills_database:

        if skill.lower() in role_description.lower():

            required_skills.append(skill)

    missing = [

        skill
        for skill in required_skills
        if skill not in resume_skills

    ]

    return sorted(set(missing))


