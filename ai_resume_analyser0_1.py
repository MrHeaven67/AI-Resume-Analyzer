# 8. JOB ROLE PREDICTION
# ============================================================

def predict_job_roles(resume_text):

    documents = [resume_text]

    role_names = []

    for role, data in job_roles.items():

        role_names.append(role)

        documents.append(data["description"])

    vectorizer = TfidfVectorizer(
        stop_words="english",
        ngram_range=(1, 2)
    )

    vectors = vectorizer.fit_transform(documents)

    resume_vector = vectors[0]

    role_vectors = vectors[1:]

    similarities = cosine_similarity(
        resume_vector,
        role_vectors
    )[0]

    results = []

    for role, score in zip(role_names, similarities):

        results.append({

            "Job Role": role,

            "Match Score": round(
                float(score) * 100,
                2
            )

        })

    results = sorted(
        results,
        key=lambda x: x["Match Score"],
        reverse=True
    )

    return results


